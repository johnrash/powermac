void
AppendUtf8(std::string& text, u32 code)
{
	if (code < 0x80)
		text += (char)code;
	else if (code < 0x800) {
		text += (char)(0xc0 | (code >> 6));
		text += (char)(0x80 | (code & 0x3f));
	} else {
		text += (char)(0xe0 | (code >> 12));
		text += (char)(0x80 | ((code >> 6) & 0x3f));
		text += (char)(0x80 | (code & 0x3f));
	}
}


// The next code point of UTF-8 'text' at 'position' (advanced); invalid
// bytes are U+FFFD.
u32
NextCode(const std::string& text, size_t& position)
{
	u8 first = (u8)text[position++];
	if (first < 0x80)
		return first;
	int extra = first >= 0xf0 ? 3 : first >= 0xe0 ? 2 : first >= 0xc0 ? 1
		: -1;
	if (extra < 0 || first >= 0xf8)
		return 0xfffd;
	u32 code = first & (0x3f >> extra);
	for (int i = 0; i < extra; i++) {
		if (position >= text.size() || ((u8)text[position] & 0xc0) != 0x80)
			return 0xfffd;
		code = (code << 6) | ((u8)text[position++] & 0x3f);
	}
	return code;
}

