std::string
HostToMacName(const std::string& utf8)
{
	std::string result;
	size_t position = 0;
	while (position < utf8.size()) {
		u32 code = NextCode(utf8, position);
		if (code == ':')
			code = '/';
		if (code < 0x80) {
			result += (char)code;
			continue;
		}
		if (code == 0x20ac)
			code = 0x00a4;		// the euro where Mac OS 7 has the currency
		char mac = '_';
		for (int i = 0; i < 128; i++) {
			if (kMacRomanHigh[i] == code) {
				mac = (char)(0x80 + i);
				break;
			}
		}
		result += mac;
	}
	return result;
}


std::string
MacToHostName(const std::string& macRoman)
{
	std::string result;
	for (char c : macRoman) {
		u8 byte = (u8)c;
		if (byte == '/')
			result += ':';
		else if (byte < 0x80)
			result += c;
		else
			AppendUtf8(result, kMacRomanHigh[byte - 0x80]);
	}
	return result;
}


int
CompareHfsNames(const std::string& a, const std::string& b)
{
	size_t length = a.size() < b.size() ? a.size() : b.size();
	for (size_t i = 0; i < length; i++) {
		if (a[i] == b[i])
			continue;
		u16 wordA = kHfsSortWord[(u8)a[i]];
		u16 wordB = kHfsSortWord[(u8)b[i]];
		if (wordA != wordB)
			return wordA < wordB ? -1 : 1;
	}
	return a.size() < b.size() ? -1 : a.size() > b.size() ? 1 : 0;
}

